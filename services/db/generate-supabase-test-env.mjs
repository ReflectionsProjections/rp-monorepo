#!/usr/bin/env node
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dbDir = path.dirname(fileURLToPath(import.meta.url));
const outputPath = path.resolve(dbDir, "../api/testing/.supabase-test.env");
const jwtSecret = crypto.randomBytes(48).toString("hex");
const expiresInSeconds = 86_400;

function base64Url(value) {
    return Buffer.from(value).toString("base64url");
}

function signSupabaseKey(role) {
    const now = Math.floor(Date.now() / 1000);
    const header = base64Url(JSON.stringify({ alg: "HS256", typ: "JWT" }));
    const payload = base64Url(
        JSON.stringify({
            iss: "rp-api-test",
            role,
            iat: now,
            exp: now + expiresInSeconds,
        })
    );
    const signature = crypto.createHmac("sha256", jwtSecret).update(`${header}.${payload}`).digest("base64url");

    return `${header}.${payload}.${signature}`;
}

const values = {
    POSTGRES_HOST: "db",
    POSTGRES_PASSWORD: "postgres",
    POSTGRES_DB: "postgres",
    POSTGRES_PORT: "5432",
    PGRST_DB_SCHEMAS: "public",
    JWT_SECRET: jwtSecret,
    JWT_EXPIRY: String(expiresInSeconds),
    POSTGREST_PORT: "3102",
    KONG_HTTP_PORT: "8100",
    KONG_HTTPS_PORT: "8143",
    SUPABASE_URL: "http://localhost:8100",
    SUPABASE_ANON_KEY: signSupabaseKey("anon"),
    SUPABASE_SERVICE_KEY: signSupabaseKey("service_role"),
    DASHBOARD_USERNAME: "test",
    DASHBOARD_PASSWORD: crypto.randomBytes(24).toString("hex"),
    OPENAI_API_KEY: "",
};

const body = [
    "# Generated by services/db/generate-supabase-test-env.mjs.",
    "# Contains ephemeral local test credentials. Do not commit this file.",
    ...Object.entries(values).map(([key, value]) => `${key}=${value}`),
    "",
].join("\n");

fs.writeFileSync(outputPath, body, { mode: 0o600 });
console.log(`Wrote ${path.relative(process.cwd(), outputPath)}`);
